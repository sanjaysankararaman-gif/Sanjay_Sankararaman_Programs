Volts = complex(input("Enter potential difference:"))
I = complex(input("Enter current;"))

print("Sum = ", Volts + I)
print("Difference = ", Volts - I)

print("Product = ", Volts * I)

print("Magnitude of Potential Difference = ", abs(Volts))

print("Real part of Volts = ", Volts.real)

print("Phase of Volts = ", Volts.imag)
